#!/usr/bin/env python3
"""Generate docs/SCREENSHOT_SHOT_LIST.md from every "shot" slide in lessons/*.json.

Re-run any time lessons change:   python3 -I tools/shot_list.py
Exit code 1 if two shot slides claim the same image path or a shot is malformed.
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LESSONS = os.path.join(ROOT, "lessons")
OUT = os.path.join(ROOT, "docs", "SCREENSHOT_SHOT_LIST.md")

# Boilerplate every capture shares; stated once at the top instead of 90 times.
DEMO_RE = re.compile(r"^Capture in the DEMO agency/sub-account only \(.*?\)\.\s*1920x1080.*?expanded\.\s*", re.S)


def lesson_key(lid):
    return tuple(int(p) if p.isdigit() else p for p in re.split(r"[.]", lid))


def split_capture(text):
    """-> (what_to_capture, pointer_target, notes)."""
    text = DEMO_RE.sub("", text or "").strip()
    target = ""
    m = re.search(r"Pointer target:\s*(.+?)(?:\.\s|\.$|$)", text, re.S)
    if m:
        target = m.group(1).strip()
        text = (text[:m.start()] + text[m.end():]).strip()
    return text.strip(), target


def pointers(p):
    if p is None:
        return []
    return p if isinstance(p, list) else [p]


def fmt_pointer(p):
    pts = []
    for q in pointers(p):
        s = f"({q.get('x')}, {q.get('y')})"
        if q.get("label"):
            s += f' “{q["label"]}”'
        if q.get("box"):
            s += f" box {q['box'].get('w')}×{q['box'].get('h')}"
        pts.append(s)
    return "<br>".join(pts)


def esc(s):
    return (s or "").replace("|", "\\|").replace("\n", " ")


def main():
    rows, errors, seen = [], [], {}
    for path in sorted(glob.glob(os.path.join(LESSONS, "*.json"))):
        with open(path) as f:
            try:
                doc = json.load(f)
            except json.JSONDecodeError as e:
                errors.append(f"{os.path.basename(path)}: invalid JSON ({e})")
                continue
        lid = doc.get("id", os.path.basename(path)[:-5])
        for i, s in enumerate(doc.get("slides", []), 1):
            if s.get("type") != "shot":
                continue
            img = s.get("image")
            if not img or not img.startswith("shots/") or not img.endswith(".png"):
                errors.append(f"{lid} slide {i}: bad image path {img!r}")
                continue
            if img in seen:
                errors.append(f"{img}: used by {seen[img]} and {lid} slide {i}")
            seen[img] = f"{lid} slide {i}"
            for q in pointers(s.get("pointer")):
                for ax in ("x", "y"):
                    if not isinstance(q.get(ax), (int, float)) or not 0 <= q[ax] <= 1:
                        errors.append(f"{img}: pointer {ax} out of 0..1")
            what, target = split_capture(s.get("capture", ""))
            # Flag shots whose label/path the author could not verify from public help pages.
            if re.search(r"\b[Cc]onfirm\b", what):
                what = "⚠ " + what
            rows.append({
                "lid": lid, "lesson": doc.get("title", ""), "slide": i, "img": img,
                "title": s.get("title", ""), "what": what, "target": target,
                "pointer": fmt_pointer(s.get("pointer")),
                "have": os.path.exists(os.path.join(LESSONS, img)),
            })
    rows.sort(key=lambda r: (lesson_key(r["lid"]), r["slide"]))

    have = sum(r["have"] for r in rows)
    L = []
    L.append("# Screenshot Shot List\n")
    L.append("_Auto-generated by `tools/shot_list.py` from `lessons/*.json`. Do not edit by hand; "
             "edit the lesson JSON and re-run._\n")
    L.append(f"**{len(rows)} screenshots across {len({r["lid"] for r in rows})} of the 47 lessons · "
             f"{have} captured · {len(rows) - have} missing.**\n")
    L.append("## Capture rules (apply to every shot)\n")
    L.append("1. Use a **demo** agency and demo sub-account only. Never capture a real client, real card "
             "numbers, or a real personal phone/email.")
    L.append("2. 1600×900 (what the capture tool produces; 16:9 at 1600×900 or larger is fine), browser zoom 100%, left menu expanded, light theme, no browser bookmarks bar.")
    L.append("3. Save as PNG in **`lessons/shots/`** using the file name in the **Image** column (the lesson JSON "
             "stores it as `shots/<name>.png`, relative to `lessons/`), e.g. `lessons/shots/2.1-01-signup-page.png`.")
    L.append("4. **Pointer** x/y are fractions of the image (0,0 = top-left, 1,1 = bottom-right) and are "
             "*estimates*. After capturing, open the shot and nudge x/y so the arrow lands on the "
             "**Pointer target** described. The renderer shows a `SCREENSHOT NEEDED` placeholder until the "
             "file exists.")
    L.append("5. HighLevel's UI changes. If a label or menu path differs from the description, capture what you "
             "see and **fix the lesson narration/slide text** to match.")
    L.append("6. Rows marked ⚠ describe a label, menu path, or setting that could **not** be verified from "
             "HighLevel's public help pages. Confirm it while capturing, and correct the lesson if it differs.\n")
    L.append("## Suggested capture order (fewest login/state changes)\n")
    L.append("Batch by screen area so you log in and set up state once. Lesson numbers below refer to "
             "the Image column prefixes:\n")
    for line in (
        "- **Signup and agency view:** 1.6, 2.1",
        "- **Snapshot import and load (agency level):** 2.3, 8.5",
        "- **Sub-account setup and tour:** 2.2, 2.4, 2.8",
        "- **Email domain and DNS (needs a throwaway demo domain):** 2.5, 2.6",
        "- **Phone number and A2P (some screens need a real submission):** 2.7",
        "- **Contacts: import a deliberately flawed demo CSV so errors appear:** 5.1 to 5.4",
        "- **Reports and follow-up (send demo messages first):** 8.1 to 8.4",
        "- **Spreadsheet screens (Modules 3-4):** generated by `tools/render_shots.py`, not captured by hand",
    ):
        L.append(line)
    L.append("")
    L.append("---\n")

    cur = None
    for r in rows:
        if r["lid"] != cur:
            cur = r["lid"]
            if L and L[-1] != "":
                L.append("")
            L.append(f"## {cur} · {r['lesson']}\n")
            L.append("| ✔ | Image | Slide | What to capture | Pointer target | Pointer (x, y) |")
            L.append("|---|---|---|---|---|---|")
        L.append("| {} | `{}` | {} | {} | {} | {} |".format(
            "✅" if r["have"] else "☐", r["img"], esc(r["title"]), esc(r["what"]),
            esc(r["target"]), esc(r["pointer"])))
    L.append("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(L))
    print(f"wrote {OUT}: {len(rows)} shots, {have} captured")
    for e in errors:
        print("ERROR", e, file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
